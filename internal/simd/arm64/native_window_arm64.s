#include "textflag.h"

// NEON 32 字节预编译字节集合判定。
//
// 与 16 字节版本逐步骤一致，只是把一个 32 字节窗口拆成两个 128 位半区分别判定，
// 再把两个 16 位位置掩码拼成 32 位结果，使热路径对每个 lane 只需一次调用。
TEXT ·nativeByteSetMask32(SB), NOSPLIT, $0-36
	MOVD window+0(FP), R0
	MOVD tables+24(FP), R1
	MOVD $0x0f, R2
	VDUP R2, V11.B16
	MOVD $0x07, R3
	VDUP R3, V12.B16
	MOVD $0x08, R4
	VDUP R4, V13.B16
	MOVD $0x01, R5
	VDUP R5, V14.B16
	MOVD $0x0102040810204080, R11
	VLD1 (R1), [V0.B16]
	ADD $16, R1, R6
	VLD1 (R6), [V1.B16]
	// 低半区：字节 0..15，掩码占返回值低 16 位。
	VLD1 (R0), [V2.B16]
	VUSHR $4, V2.B16, V3.B16
	VAND V11.B16, V2.B16, V4.B16
	VTBL V3.B16, [V0.B16], V5.B16
	VTBL V3.B16, [V1.B16], V6.B16
	VCMHS V13.B16, V4.B16, V7.B16
	VBSL V5.B16, V6.B16, V7.B16
	VAND V12.B16, V4.B16, V8.B16
	VUSHL V8.B16, V14.B16, V9.B16
	VCMTST V9.B16, V7.B16, V10.B16
	VUSHR $7, V10.B16, V10.B16
	VMOV V10.D[0], R9
	VMOV V10.D[1], R10
	MUL R11, R9, R9
	MUL R11, R10, R10
	LSR $56, R9, R9
	LSR $56, R10, R10
	LSL $8, R10, R10
	ORR R10, R9, R7
	// 高半区：字节 16..31，掩码左移 16 位后合并。
	ADD $16, R0, R6
	VLD1 (R6), [V2.B16]
	VUSHR $4, V2.B16, V3.B16
	VAND V11.B16, V2.B16, V4.B16
	VTBL V3.B16, [V0.B16], V5.B16
	VTBL V3.B16, [V1.B16], V6.B16
	VCMHS V13.B16, V4.B16, V7.B16
	VBSL V5.B16, V6.B16, V7.B16
	VAND V12.B16, V4.B16, V8.B16
	VUSHL V8.B16, V14.B16, V9.B16
	VCMTST V9.B16, V7.B16, V10.B16
	VUSHR $7, V10.B16, V10.B16
	VMOV V10.D[0], R9
	VMOV V10.D[1], R10
	MUL R11, R9, R9
	MUL R11, R10, R10
	LSR $56, R9, R9
	LSR $56, R10, R10
	LSL $8, R10, R10
	ORR R10, R9, R9
	LSL $16, R9, R9
	ORR R9, R7, R7
	MOVW R7, ret+32(FP)
	RET


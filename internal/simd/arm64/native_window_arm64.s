	VMOV V10.D[1], R10
	MUL R11, R9, R9
	MUL R11, R10, R10
	LSR $56, R9, R9
	LSR $56, R10, R10
	LSL $8, R10, R10
	ORR R10, R9, R12
	LSL $16, R12, R12
	ORR R12, R7, R7
	// 半区 2：字节 32..47，掩码左移 32 位后合并。

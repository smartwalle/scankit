#include "textflag.h"

// SSSE3 32 字节预编译字节集合判定。
//
// 与 16 字节版本逐步骤一致，只是把一个 32 字节窗口拆成两个 128 位半区分别判定，
// 再把两个 16 位位置掩码拼成 32 位结果，使热路径对每个 lane 只需一次调用。
// 常量全部用立即数装填，避免热路径额外引用数据段常量。
TEXT ·nativeByteSetMask32(SB), NOSPLIT, $0-36
	MOVQ window+0(FP), AX
	MOVQ tables+24(FP), CX
	MOVQ $0x0f0f0f0f0f0f0f0f, DX
	MOVQ DX, X13
	PUNPCKLQDQ X13, X13
	MOVQ $0x0707070707070707, DX
	MOVQ DX, X14
	PUNPCKLQDQ X14, X14
	MOVQ $0x8040201008040201, DX
	MOVQ DX, X15
	PUNPCKLQDQ X15, X15
	MOVOU (CX), X7
	MOVOU 16(CX), X8
	PXOR X12, X12
	// 低半区：字节 0..15，掩码占返回值低 16 位。
	MOVOU (AX), X0
	MOVOU X0, X1
	PSRLW $4, X0
	PAND X13, X0
	MOVOU X1, X2
	PAND X13, X2
	MOVOU X7, X4
	PSHUFB X0, X4
	MOVOU X8, X5
	PSHUFB X0, X5
	MOVOU X2, X6
	PCMPGTB X14, X6
	MOVOU X5, X9
	PAND X6, X9
	PANDN X4, X6
	POR X9, X6
	MOVOU X2, X10
	PAND X14, X10
	MOVOU X15, X11
	PSHUFB X10, X11
	PAND X11, X6
	PCMPEQB X12, X6
	PMOVMSKB X6, R8
	XORW $0xffff, R8
	// 高半区：字节 16..31，掩码左移 16 位后合并。
	MOVOU 16(AX), X0
	MOVOU X0, X1
	PSRLW $4, X0
	PAND X13, X0
	MOVOU X1, X2
	PAND X13, X2
	MOVOU X7, X4
	PSHUFB X0, X4
	MOVOU X8, X5
	PSHUFB X0, X5
	MOVOU X2, X6
	PCMPGTB X14, X6
	MOVOU X5, X9
	PAND X6, X9
	PANDN X4, X6
	POR X9, X6
	MOVOU X2, X10
	PAND X14, X10
	MOVOU X15, X11
	PSHUFB X10, X11
	PAND X11, X6
	PCMPEQB X12, X6
	PMOVMSKB X6, DX
	XORW $0xffff, DX
	SHLL $16, DX
	ORL DX, R8
	MOVL R8, ret+32(FP)
	RET

// AVX2 32 字节预编译字节集合判定。
//
// 与 SSE 版本语义完全相同，但一个 256 位寄存器即可覆盖整个窗口：PSHUFB 按 128 位
// 半区独立查表，因此把 16 字节行表复制到两个半区后即可一次完成 32 字节判定，
// VPMOVMSKB 直接给出 32 位位置掩码。常量同样用立即数广播，避免数据段引用。
TEXT ·nativeByteSetMask32AVX2(SB), NOSPLIT, $0-36
	MOVQ window+0(FP), AX
	MOVQ tables+24(FP), CX
	MOVQ $0x0f0f0f0f0f0f0f0f, DX
	VMOVQ DX, X13
	VPBROADCASTQ X13, Y13
	MOVQ $0x0707070707070707, DX
	VMOVQ DX, X14
	VPBROADCASTQ X14, Y14
	MOVQ $0x8040201008040201, DX
	VMOVQ DX, X15
	VPBROADCASTQ X15, Y15
	VMOVDQU (CX), X7
	VINSERTI128 $1, (CX), Y7, Y7
	VMOVDQU 16(CX), X8
	VINSERTI128 $1, 16(CX), Y8, Y8
	VMOVDQU (AX), Y0
	VPSRLW $4, Y0, Y1
	VPAND Y13, Y1, Y1
	VPAND Y13, Y0, Y2
	VPSHUFB Y1, Y7, Y4
	VPSHUFB Y1, Y8, Y5
	VPCMPGTB Y14, Y2, Y6
	VPAND Y6, Y5, Y9
	VPANDN Y4, Y6, Y10
	VPOR Y10, Y9, Y6
	VPAND Y14, Y2, Y10
	VPSHUFB Y10, Y15, Y11
	VPAND Y11, Y6, Y6
	VPXOR Y12, Y12, Y12
	VPCMPEQB Y12, Y6, Y6
	VPMOVMSKB Y6, R8
	NOTL R8
	MOVL R8, ret+32(FP)
	VZEROUPPER
	RET

// AVX512BW 64 字节预编译字节集合判定。
//
// 与 AVX2 版本逐步骤一致，只是把四个 128 位半区一次装进 zmm：VPSHUFB 按 128 位半区
// 独立查表，因此把 16 字节行表复制到四个半区后即可一次完成 64 字节判定。与 128 位版本
// 的收尾差别是末尾用 VPTESTMB 直接产生 k 掩码，再经 KMOVQ 取出 64 位位置掩码，省掉
// 逐字节比较与取反。返回值的位 i 对应窗口内偏移 i 的字节命中集合。
TEXT ·nativeByteSetMask64AVX512(SB), NOSPLIT, $0-40
	MOVQ window+0(FP), AX
	MOVQ tables+24(FP), CX
	MOVQ $0x0f0f0f0f0f0f0f0f, DX
	MOVQ DX, X13
	VPBROADCASTQ X13, Z13
	MOVQ $0x0707070707070707, DX
	MOVQ DX, X14
	VPBROADCASTQ X14, Z14
	MOVQ $0x8040201008040201, DX
	MOVQ DX, X15
	VPBROADCASTQ X15, Z15
	// 低 16 字节行表：先装载低半区，再复制到高半区并由 VINSERTI64X4 填满 zmm。
	VMOVDQU (CX), X7
	VINSERTI128 $1, (CX), Y7, Y7
	VINSERTI64X4 $1, Y7, Z7, Z7
	// 高 16 字节行表（低半字节第 3 位为 1 的分支）做同样的 128 位半区复制。
	VMOVDQU 16(CX), X8
	VINSERTI128 $1, 16(CX), Y8, Y8
	VINSERTI64X4 $1, Y8, Z8, Z8
	VMOVDQU64 (AX), Z0
	VPSRLW $4, Z0, Z1
	VPANDQ Z13, Z1, Z1
	VPANDQ Z13, Z0, Z2
	VPSHUFB Z1, Z7, Z4
	VPSHUFB Z1, Z8, Z5
	// 低半字节第 3 位为 1 时选高半行表：先比较出 k 掩码，再展开成字节掩码做选择。
	VPCMPGTB Z14, Z2, K2
	VPMOVM2B K2, Z6
	VPANDQ Z6, Z5, Z9
	VPANDNQ Z4, Z6, Z10
	VPORQ Z10, Z9, Z6
	// 位选：1<<(低半字节&7)，与行位图相与后非零即命中。
	VPANDQ Z14, Z2, Z10
	VPSHUFB Z10, Z15, Z11
	VPANDQ Z11, Z6, Z6
	VPTESTMB Z6, Z6, K1
	KMOVQ K1, R8
	MOVQ R8, ret+32(FP)
	VZEROUPPER
	RET

// AVX512VBMI 64 字节预编译字节集合判定。
//
// VBMI 的 VPERMB 可以在一条指令内完成 64 字节查表，因此把 32 字节行表复制两份填满
// zmm 后，只需把每个字节折算成表下标（高半字节 | 低半字节第 3 位 << 4）即可一次取出
// 行位图，省掉 AVX512BW 版本的两路 VPSHUFB 与掩码选择。位选与收尾与 BW 版本一致。
TEXT ·nativeByteSetMask64VBMI(SB), NOSPLIT, $0-40
	MOVQ window+0(FP), AX
	MOVQ tables+24(FP), CX
	MOVQ $0x0f0f0f0f0f0f0f0f, DX
	MOVQ DX, X13
	VPBROADCASTQ X13, Z13
	MOVQ $0x0101010101010101, DX
	MOVQ DX, X12
	VPBROADCASTQ X12, Z12
	MOVQ $0x0707070707070707, DX
	MOVQ DX, X14
	VPBROADCASTQ X14, Z14
	MOVQ $0x8040201008040201, DX
	MOVQ DX, X15
	VPBROADCASTQ X15, Z15
	VMOVDQU (CX), Y7
	VINSERTI64X4 $1, Y7, Z7, Z7
	VMOVDQU64 (AX), Z0
	VPSRLW $4, Z0, Z1
	VPANDQ Z13, Z1, Z1
	VPSRLW $3, Z0, Z3
	VPANDQ Z12, Z3, Z3
	VPSLLW $4, Z3, Z3
	VPORD Z3, Z1, Z3
	VPERMB Z3, Z7, Z4
	VPANDQ Z14, Z0, Z10
	VPSHUFB Z10, Z15, Z11
	VPANDQ Z11, Z4, Z4
	VPTESTMB Z4, Z4, K1
	KMOVQ K1, R8
	MOVQ R8, ret+32(FP)
	VZEROUPPER
	RET
